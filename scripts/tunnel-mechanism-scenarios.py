"""Run source-bound 250 mm tunnel fixtures, opening/restore and height controls.

Build: cargo build -p rm-simulator-app --example robot_tunnel --locked.
Packages must first be generated by rm-map-tools' bind_tunnel.py.
"""
import argparse
import json
from pathlib import Path
import subprocess
import tempfile


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--binary',type=Path,default=Path('target/nix/debug/examples/robot_tunnel'))
    parser.add_argument('--sources',type=Path,default=Path('local-assets/robot-cad-survey'))
    args=parser.parse_args();results={}
    def run(name,config,mode,roof,expected):
        process=subprocess.run([str(args.binary.resolve()),str(config),mode,str(roof)],text=True,capture_output=True)
        if not process.stdout.strip():raise RuntimeError(process.stderr)
        result=json.loads(process.stdout.splitlines()[-1])
        assert result['passed'] is expected, (name,result,process.stderr)
        if expected:assert process.returncode==0,(name,process.stderr)
        assert result['restored_mid_transform'],result
        results[name]=result
    heavy=args.sources/'bound-tunnel-heavy/chassis.json';infantry=args.sources/'bound-tunnel-infantry/chassis.json'
    run('pie_stowed',heavy,'stowed',.25,True)
    assert results['pie_stowed']['blocked_unfold'],results['pie_stowed']
    run('pie_open',heavy,'open',.25,False)
    run('future_neutral',infantry,'stowed',.25,True)
    run('future_lower_roof_control',infantry,'stowed',.24,False)
    sentry=args.sources/'bound-tunnel-sentry/chassis.json'
    run('ega_stowed',sentry,'stowed',.25,True)
    assert results['ega_stowed']['blocked_unfold'],results['ega_stowed']
    assert results['ega_stowed']['interior_samples']>0,results['ega_stowed']
    assert results['ega_stowed']['max_interior_height_m']<=.252,results['ega_stowed']
    run('ega_open_control',sentry,'open',.25,False)
    with tempfile.TemporaryDirectory(prefix='rm-tunnel-') as folder:
        hero=Path(folder)/'hero.json'
        subprocess.run([str(args.binary.resolve()),'export-hero',str(hero)],check=True)
        run('hero_folded',hero,'stowed',.25,True)
        run('hero_open',hero,'open',.25,False)
    print(json.dumps(results,indent=2))


if __name__=='__main__':main()
